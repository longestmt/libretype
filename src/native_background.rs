unsafe fn read_plain(board: id) -> Option<String> {
    if board == nil {
        return None;
    }
    let count_before: isize = msg_send![board, changeCount];
    let types: id = msg_send![board, types];
    if types == nil {
        return None;
    }
    for marker in [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ] {
        let kind = ns(marker);
        let found: BOOL = msg_send![types, containsObject:kind];
        let _: () = msg_send![kind, release];
        if found == YES {
            return None;
        }
    }
    // Plain text only. Never request a file, image, rich-text conversion or history.
    let kind = ns("public.utf8-plain-text");
    let found: BOOL = msg_send![types, containsObject:kind];
    let value: id = if found == YES {
        msg_send![board, stringForType:kind]
    } else {
        nil
    };
    let _: () = msg_send![kind, release];
    if value == nil {
        return None;
    }
    let length: usize = msg_send![value, length];
    let count_after: isize = msg_send![board, changeCount];
    if length > 65_536 || count_before != count_after {
        return None;
    }
    Some(ns_text(value))
}

pub(super) unsafe fn collect(config: &Config, ctx: &Context) -> Background {
    if !background::allowed(config, &ctx.app, ctx.website.as_deref()) {
        return Background::default();
    }
    // A request may outlive its last timer capture. Check field, selection, site
    // and secure-input status immediately before and after reading the clipboard.
    if capture_selected(config, 0.08, true).is_none_or(|now| !ctx.same(&now)) {
        return Background::default();
    }
    let result = Background::collect(config, &ctx.app, ctx.website.as_deref(), || {
        let board: id = msg_send![class!(NSPasteboard), generalPasteboard];
        read_plain(board)
    });
    if capture_selected(config, 0.08, true).is_none_or(|now| !ctx.same(&now)) {
        return Background::default();
    }
    result
}

